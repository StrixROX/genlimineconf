#!/usr/bin/env bash

LIBDIR_PATH="@LIBDIR_PATH@"
CMDDIR_PATH="@CMDDIR_PATH@"

source "$LIBDIR_PATH/00-core.sh"
source "$LIBDIR_PATH/01-utils.sh"
source "$CMDDIR_PATH/refresh_entries.sh"

generate_limine_conf() {
  if [ -z "$ENTRIESDIR" ]; then
    # create a temp dir for storing the entries
    # (makefile gives the temp dir template)
    local ENTRIESDIR="$(mktemp -d "@ENTRIESDIR_TMP@")"

    # remove the entries dir when this function finishes
    trap 'rm -rf "$ENTRIESDIR"' RETURN

    # TODO: should prolly rename this to scan_for_kernels
    # but this is technically correct too...
    refresh_entries
  else
    init_check
  fi

  if ! ls "$ENTRIESDIR"/*.entry >/dev/null 2>&1; then
    >&2 echo "Error: Missing: boot entries in: $ENTRIESDIR"
    exit 1
  fi

  # backup current config
  local limine_conf="$(get_limine_conf_path)/limine.conf"
  local limine_conf_bak="$limine_conf.bak"

  cp "$limine_conf" "$limine_conf_bak"

  echo "Info: Created backup: $limine_conf_bak"

  # write new limine.conf
  write_limine_conf() {
    echo "### This file was generated by genlimineconf" > $limine_conf

    # write user options
    local CONFDIR="@CONFDIR@"

    local all_user_confs="$(ls -dp "$CONFDIR"/*.conf 2>/dev/null)"
    if [ -n "$all_user_confs" ]; then
      cat $all_user_confs >> $limine_conf
    fi

    # add a "Void Linux" dir to the limine displayed tree
    echo '/+Void Linux' >> $limine_conf

    # write all boot entries in reverse lexical order
    local all_boot_entries="$(ls -rdp "$ENTRIESDIR"/*.entry)"
    cat $all_boot_entries >> $limine_conf

    echo "Info: Generated limine config: $limine_conf"
  }

  # if any errors, restore the backup
  if ! write_limine_conf; then
    >&2 echo "Error: Failed to generate limine config: $limine_conf"

    cp "$limine_conf_bak" "$limine_conf"

    echo "Info: Restored limine config backup: $limine_conf_bak"

    return 1
  fi
}
