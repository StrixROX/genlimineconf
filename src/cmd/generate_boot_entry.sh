#!/usr/bin/env bash

LIBDIR_PATH="@LIBDIR_PATH@"

source "$LIBDIR_PATH/00-core.sh"
source "$LIBDIR_PATH/01-utils.sh"

generate_boot_entry() {
  if [ -z "$1" ]; then
    >&2 echo "Error: Missing arg: 1: pkgname"
    exit 1
  elif [ -z "$2" ]; then
    >&2 echo "Error: Missing arg: 2: version"
    exit 1
  fi

  local pkgname="$1"
  local version="$2"

  init_check

  local ENTRIESDIR="$ENTRIESDIR" # environment supplied var

  local entry="$ENTRIESDIR/${pkgname}_${version}.entry"

  local root_part_uuid="$(get_root_part_uuid)"

  local KERNEL_PATH="@KERNEL_PATH@" # relative to /boot

  # TODO: I wanna just move this out to a src/templates
  # and do sed substitutions here explicitly
  echo "//$pkgname $version
### This entry was generated by genlimineconf
comment: Kernel version: $version
comment: kernel-name: $pkgname
protocol: linux
path: boot():$KERNEL_PATH/vmlinuz-$version
module_path: boot():$KERNEL_PATH/initramfs-$version.img
cmdline: quiet rw root=UUID=$root_part_uuid
" > $entry

  echo "Info: Generated limine boot entry: $entry"
}

